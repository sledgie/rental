/**
 * Single time anchor for the whole prototype so that lease expiry windows,
 * overdue balances and "this month" figures stay coherent on any run date.
 */
export const TODAY = new Date();
TODAY.setHours(0, 0, 0, 0);

/** Configurable expiry warning period (days) used to derive "Expiring". */
export const EXPIRY_WARNING_DAYS = 60;

const d = (offsetDays: number) => addDays(TODAY, offsetDays);
const iso = (dt: Date) => isoDate(dt);

/** nth day of the month `offset` months from today. */
function monthDay(offset: number, day: number): string {
  const base = new Date(TODAY.getFullYear(), TODAY.getMonth() + offset, 1);
  const last = new Date(base.getFullYear(), base.getMonth() + 1, 0).getDate();
  base.setDate(Math.min(day, last));
  return iso(base);
}

function monthName(offset: number): string {
  return new Date(TODAY.getFullYear(), TODAY.getMonth() + offset, 1).toLocaleDateString("en-CA", {
    month: "long",
    year: "numeric",
  });
}

