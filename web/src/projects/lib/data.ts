const expense = (e: Partial<Expense> & Pick<Expense, "id" | "projectId" | "date" | "category" | "description" | "vendor" | "unitPriceCents">): Expense => {
  const quantity = e.quantity ?? 1;
  const subtotal = Math.round(quantity * e.unitPriceCents);
  const discount = e.discountCents ?? 0;
  const rate = e.taxRate ?? 13;
  const tax = Math.round(((subtotal - discount) * rate) / 100);
  return {
    quantity,
    uom: e.uom ?? "ea",
    subtotalCents: subtotal,
    discountCents: discount,
    taxRate: rate,
    taxAmountCents: tax,
    totalCents: subtotal - discount + tax,
    ...e,
    receiptNumber: e.receiptNumber ?? "",
    approval: e.approval ?? "Approved",
    notes: e.notes ?? "",
    createdBy: e.createdBy ?? "Avery Chen",
    createdAt: e.createdAt ?? `${e.date}T10:00:00`,
  };
};

