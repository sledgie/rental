function acct(
  accountId: string,
  accountCode: string,
  accountName: string,
  accountType: ChartAccount["accountType"],
  extra: Partial<ChartAccount> = {},
): ChartAccount {
  const normalBalance =
    extra.normalBalance ??
    (accountType === "asset" || accountType === "expense" ? "debit" : "credit");
  return {
    accountId,
    accountCode,
    accountName,
    accountType,
    parentAccountId: extra.parentAccountId ?? null,
    normalBalance,
    isPostingAccount: extra.isPostingAccount ?? true,
    isActive: true,
    pnlSection: extra.pnlSection ?? null,
    bsSection: extra.bsSection ?? null,
    isOperating: extra.isOperating ?? (accountType === "revenue" || extra.pnlSection != null),
    cashFlowClass: extra.cashFlowClass ?? "none",
  };
}

